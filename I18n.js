function resolveLanguage(lang, sysLocale) {
  var requested = String(lang || "system").toLowerCase().replace(/_/g, "-").trim();
  var value = requested === "system" || !requested ? String(sysLocale || "en").toLowerCase().replace(/_/g, "-").trim() : requested;
  // Only Simplified Chinese is shipped. Script/region mismatches use the source locale.
  if (/^zh-(?:hant|tw|hk|mo)(?:-|$)/.test(value)) return "en";
  if (strings[value]) return value;
  var prefix = value.split("-")[0];
  if (strings[prefix]) return prefix;
  return "en";
}

function t(key, lang) {
  var l = resolveLanguage(lang, typeof Qt !== "undefined" && Qt.locale ? Qt.locale().name : "en");
  if (strings[l] && strings[l][key] !== undefined) {
    return strings[l][key];
  }
  if (strings["en"] && strings["en"][key] !== undefined) {
    return strings["en"][key];
  }
  return key;
}
