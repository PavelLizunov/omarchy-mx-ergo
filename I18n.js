function resolveLanguage(lang, sysLocale) {
  var l = String(lang || "system").toLowerCase().trim();
  if (l !== "system" && l !== "") {
    if (strings[l]) return l;
    if (l.length > 2 && strings[l.substring(0, 2)]) return l.substring(0, 2);
  }
  var s = String(sysLocale || "en").toLowerCase().replace(/_/g, "-").trim();
  if (strings[s]) return s;
  var prefix = s.split("-")[0];
  if (strings[prefix]) return prefix;
  return "en";
}

function t(key, lang) {
  var l = resolveLanguage(lang, typeof Qt !== "undefined" && Qt.locale ? Qt.locale().name : "en");
  if (strings[l] && strings[l][key] !== undefined) {
    return strings[l][key];
  }
  if (strings["en"] && strings["en"][key] !== undefined) {
    return strings["en"][key];
  }
  return key;
}
